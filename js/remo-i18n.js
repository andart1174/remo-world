const REMO_I18N = {
  current: (function () {
    const saved = localStorage.getItem('remo_lang');
    if (saved === 'en' || saved === 'fr') return saved;
    const nav = (navigator.language || 'en').toLowerCase();
    return nav.startsWith('fr') ? 'fr' : 'en';
  })(),

  getLang() {
    return this.current;
  },

  setLang(lang) {
    if (lang !== 'en' && lang !== 'fr') lang = 'en';
    this.current = lang;
    localStorage.setItem('remo_lang', lang);
    document.documentElement.lang = lang;
    this.applyDOM();
    window.dispatchEvent(new CustomEvent('remo:langchange', { detail: { lang } }));
  },

  toggle() {
    this.setLang(this.current === 'en' ? 'fr' : 'en');
  },

  t(key, vars = {}) {
    const pack = REMO_DICT[this.current] || REMO_DICT.en;
    let str = pack[key] !== undefined ? pack[key] : (REMO_DICT.en[key] || key);
    Object.keys(vars).forEach((k) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), vars[k]);
    });
    return str;
  },

  applyDOM(root = document) {
    document.documentElement.lang = this.current;
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) el.textContent = this.t(key);
    });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      if (key) el.innerHTML = this.t(key);
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key) el.placeholder = this.t(key);
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      if (key) el.title = this.t(key);
    });
    document.querySelectorAll('.remo-lang-pill').forEach((btn) => {
      const btnLang = btn.getAttribute('data-lang');
      btn.classList.toggle('active', btnLang === this.current);
    });
  }
};

function t(key, vars) {
  return REMO_I18N.t(key, vars);
}

window.REMO_I18N = REMO_I18N;
window.t = t;
